/** Verify bundled artwork and fonts and generate private icon imports. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import assert from "node:assert/strict";

const root = resolve(import.meta.dirname, "../src/client/appearance");
const read = name => readFileSync(resolve(root, name), "utf8");
const provenance = JSON.parse(read("assets/icons/manifest.json"));
const icons = {};
for (const [file, hash] of Object.entries(provenance.files)) {
  assert.match(file, /^[a-z0-9-]+\.png$/);
  const bytes = readFileSync(resolve(root, "assets/icons", file));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), hash, `Changed icon: ${file}`);
  assert.equal(bytes.toString("hex", 0, 8), "89504e470d0a1a0a", `Invalid PNG: ${file}`);
  assert.equal(bytes.readUInt32BE(16), 128, `Width: ${file}`);
  assert.equal(bytes.readUInt32BE(20), 128, `Height: ${file}`);
  icons[file.slice(0, -4)] = `icons/${file}`;
}
const names = Object.keys(icons);
writeFileSync(resolve(root, 'icons.ts'), '/** Bundled, verified artwork. Generated by build-appearance.mjs. */\n' + names.map((name,i)=>'import icon'+i+' from '+JSON.stringify('./assets/'+icons[name])+';').join('\n')+'\nexport const BUNDLED_ICONS = {\n'+names.map((name,i)=>'  '+JSON.stringify(name)+': icon'+i+',').join('\n')+'\n} as const;\n');
const fonts = JSON.parse(read('assets/fonts/manifest.json'));
for (const {file,sha256} of fonts.files) assert.equal(createHash('sha256').update(readFileSync(resolve(root,'assets/fonts',file))).digest('hex'),sha256,file);
for(const f of ['OFL.txt','OFL-NotoSansSC.txt']) assert.ok(existsSync(resolve(root,'assets/fonts',f)));
console.log('Bundled appearance verified: '+names.length+' icons, '+fonts.files.length+' fonts.');
