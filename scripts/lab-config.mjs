#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";
import { labPaths, prepareLabPath } from "./lab-paths.mjs";
import { setupLab } from "./lab-setup.mjs";

function yamlString(value) {
  return JSON.stringify(value);
}

export const LAB_WRITABLE_PATH_KEYS = Object.freeze([
  "libraryRoot",
  "creatorRoot",
  "atlasRoot",
  "trellisProjectsRoot",
  "dataDir",
  "subtitleSkillDir",
  "coverSkillDir",
  "videoPublisherSkillDir",
]);

export const LAB_PROFILE_WORKSPACE = "packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n";

export const DESKTOP_PROFILE_SELECTION_STATE = Object.freeze({
  version: 2,
  active: "web",
});

export const DESKTOP_MARKET_SELECTION_STATE = Object.freeze({
  version: 1,
  requested: "disabled",
  legacyDefaulted: false,
});

export const DESKTOP_SETTINGS_DOCUMENT = "dsh-desktop:\n  mode: compatibility\n";

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function desktopSettingMatches(settings, key, expected) {
  return !Object.hasOwn(settings, key) || settings[key] === expected;
}

/** Validates Desktop settings that must remain safe in either Lab mode. */
export function assertSafeDesktopSettings(document) {
  let parsed;
  try {
    parsed = parseYaml(document);
  } catch (error) {
    throw new Error(`Desktop settings.yaml 不可读。${String(error)}`);
  }
  const desktop = isRecord(parsed) && isRecord(parsed["dsh-desktop"])
    ? parsed["dsh-desktop"]
    : undefined;
  const notifications = isRecord(parsed) && isRecord(parsed["dsh-desktop-notifications"])
    ? parsed["dsh-desktop-notifications"]
    : undefined;
  if (
    !desktop
    || desktop.mode !== "compatibility"
    || !desktopSettingMatches(desktop, "windowsMaterial", "off")
    || !desktopSettingMatches(desktop, "openBrowser", false)
    || !desktopSettingMatches(desktop, "networkExposure", "loopback")
    || (notifications && notifications.enabled !== false)
  ) {
    throw new Error("Desktop settings.yaml 未保持隔离兼容配置；请重新检查 Desktop 设置。");
  }
}

export function createLabSafetyConfig(paths) {
  return {
    externalActionsEnabled: false,
    libraryRoot: paths.library,
    creatorRoot: paths.library,
    atlasRoot: paths.atlas,
    trellisProjectsRoot: paths.trellis,
    dataDir: paths.data,
    subtitleSkillDir: join(paths.skills, "subtitle"),
    coverSkillDir: join(paths.skills, "cover"),
    videoPublisherSkillDir: join(paths.skills, "video-publisher"),
    obsidianExecutable: "",
    enabledPublishTargets: [],
    credentials: {},
    lab: { isolated: true, repositoryRoot: paths.root },
  };
}

export function createProfileManifest(paths, name) {
  return {
    name,
    private: true,
    dependencies: { "dsh-muzi-creator": `link:${paths.root.replaceAll("\\", "/")}` },
    dsh: {
      profile: {
        bundles: ["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-web-app", "dsh-muzi-creator"],
      },
    },
  };
}

export function createLabProfileManifest(paths) {
  return createProfileManifest(paths, "dsh-profile-web-muzi-creator-lab");
}

export function createMuziProfilePatch(config, banner) {
  return [
    banner,
    "- id: dsh-muzi-creator",
    "  config:",
    `    libraryRoot: ${yamlString(config.libraryRoot)}`,
    `    creatorRoot: ${yamlString(config.creatorRoot)}`,
    `    atlasRoot: ${yamlString(config.atlasRoot)}`,
    `    dataDir: ${yamlString(config.dataDir)}`,
    `    subtitleSkillDir: ${yamlString(config.subtitleSkillDir)}`,
    `    coverSkillDir: ${yamlString(config.coverSkillDir)}`,
    `    videoPublisherSkillDir: ${yamlString(config.videoPublisherSkillDir)}`,
    `    trellisProjectsRoot: ${yamlString(config.trellisProjectsRoot)}`,
    `    obsidianExecutable: ${yamlString(config.obsidianExecutable)}`,
    "    enabledPublishTargets: []",
    "    externalActionsEnabled: false",
    "",
  ].join("\n");
}

export function createLabProfilePatch(config) {
  return createMuziProfilePatch(
    config,
    "# Generated by pnpm lab:config. All writable Muzi Creator paths remain under .lab.",
  );
}

/** Returns the Desktop-owned selected-profile state used by Desktop 2.0.4. */
export function createDesktopProfileSelectionState() {
  return { ...DESKTOP_PROFILE_SELECTION_STATE };
}

/** Returns Desktop 2.0.4's explicit disabled-Market selection. */
export function createDesktopMarketSelectionState() {
  return { ...DESKTOP_MARKET_SELECTION_STATE };
}

export async function writeLabConfig(repositoryRoot) {
  const paths = await setupLab(repositoryRoot);
  const config = createLabSafetyConfig(paths);
  for (const directory of [config.subtitleSkillDir, config.coverSkillDir, config.videoPublisherSkillDir]) {
    await prepareLabPath(paths.root, directory);
    await mkdir(directory, { recursive: true });
  }
  const manifest = createLabProfileManifest(paths);
  const patch = createLabProfilePatch(config);
  for (const target of [
    paths.profileManifest,
    paths.profilePatch,
    paths.profileWorkspace,
    paths.desktopProfileManifest,
    paths.desktopProfilePatch,
    paths.desktopProfileWorkspace,
    paths.desktopProfileSelection,
    paths.desktopMarketSelection,
    paths.desktopSettings,
    paths.safetyManifest,
  ]) {
    await prepareLabPath(paths.lab, target);
    await mkdir(dirname(target), { recursive: true });
  }
  await writeFile(paths.profileManifest, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  await writeFile(paths.profilePatch, patch, "utf8");
  await writeFile(paths.profileWorkspace, LAB_PROFILE_WORKSPACE, "utf8");
  await writeFile(paths.desktopProfileManifest, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  await writeFile(paths.desktopProfilePatch, patch, "utf8");
  await writeFile(paths.desktopProfileWorkspace, LAB_PROFILE_WORKSPACE, "utf8");
  await writeFile(paths.desktopProfileSelection, `${JSON.stringify(createDesktopProfileSelectionState(), null, 2)}\n`, "utf8");
  await writeFile(paths.desktopMarketSelection, `${JSON.stringify(createDesktopMarketSelectionState(), null, 2)}\n`, "utf8");
  await writeFile(paths.desktopSettings, DESKTOP_SETTINGS_DOCUMENT, "utf8");
  await writeFile(paths.safetyManifest, `${JSON.stringify(config, null, 2)}\n`, "utf8");
  console.log(`Lab Web 与 Desktop profile 已写入：${paths.profile}`);
  return { paths, config };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await writeLabConfig(process.cwd());
