async function readOptionalFile(target) {
  let info;
  try {
    info = await lstat(target);
  } catch (error) {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  }
  if (!info.isFile() || info.isSymbolicLink()) {
    throw new Error(`个人模式文件必须是普通文件；已拒绝读取或覆盖：${target}`);
  }
  return readFile(target, "utf8");
}

async function writeAbsentOrEqual(target, content, label) {
  const existing = await readOptionalFile(target);
  if (existing !== undefined && existing !== content) {
    throw new Error(`${label}已存在且与当前个人模式配置冲突；已拒绝覆盖：${target}`);
  }
  if (existing === undefined) await writeFile(target, content, "utf8");
}

async function writeAbsentOrSafeSettings(target) {
  const existing = await readOptionalFile(target);
  if (existing === undefined) {
    await writeFile(target, DESKTOP_SETTINGS_DOCUMENT, "utf8");
    return;
  }
  try {
    assertSafeDesktopSettings(existing);
  } catch (error) {
    throw new Error(`个人 Desktop 设置已存在且不安全；已拒绝覆盖：${target}。${String(error)}`);
  }
}

export async function assertPersonalOverlayDoesNotConflict(paths, config) {
  const overlayPath = join(paths.personalData, "overlay.json");
  const source = await readOptionalFile(overlayPath);
  if (source === undefined) return;
  let overlay;
  try {
    overlay = JSON.parse(source);
  } catch (error) {
    throw new Error(`个人模式 overlay 不可读，已拒绝覆盖：${overlayPath}。${String(error)}`);
  }
  const expected = {
    libraryRoot: config.libraryRoot,
    trellisProjectsRoot: config.trellisProjectsRoot,
    obsidianExecutable: config.obsidianExecutable,
  };
  for (const [key, value] of Object.entries(expected)) {
    if (overlay[key] !== undefined && (typeof overlay[key] !== "string" || !samePath(overlay[key], value))) {
      throw new Error(`个人模式 overlay 的 ${key} 与固定真实路径冲突；已拒绝覆盖：${overlayPath}`);
    }
  }
}

/** Writes a fail-closed personal Desktop profile that points at the configured real roots. */
export async function writePersonalLabConfig(repositoryRoot, configuredPaths = PERSONAL_WINDOWS_PATHS) {
  const paths = labPaths(repositoryRoot);
  const config = createPersonalConfig(paths, configuredPaths);
  await assertPersonalTargetPaths(config);
  await assertPersonalOverlayDoesNotConflict(paths, config);

  for (const directory of [
    paths.personal,
    paths.personalHome,
    paths.personalProfile,
    paths.personalProfileModules,
    paths.personalUserData,
    paths.personalData,
    paths.personalSkills,
    config.subtitleSkillDir,
    config.coverSkillDir,
    config.videoPublisherSkillDir,
  ]) {
    await prepareOrdinaryLabDirectory(paths.root, directory);
  }
  await ensurePluginLink(paths.personalPluginLink, paths.root);

  const documents = [
    [paths.personalProfileManifest, `${JSON.stringify(createPersonalProfileManifest(paths), null, 2)}\n`, "个人 Profile manifest"],
    [paths.personalProfilePatch, createPersonalProfilePatch(config), "个人 Profile patch"],
    [paths.personalProfileWorkspace, LAB_PROFILE_WORKSPACE, "个人 Profile workspace"],
    [paths.personalProfileSelection, `${JSON.stringify(createDesktopProfileSelectionState(), null, 2)}\n`, "个人 Profile 选择状态"],
    [paths.personalMarketSelection, `${JSON.stringify(createDesktopMarketSelectionState(), null, 2)}\n`, "个人 Market 状态"],
    [paths.personalConfig, `${JSON.stringify(config, null, 2)}\n`, "个人配置"],
  ];
  for (const [target, content, label] of documents) {
    await prepareLabPath(paths.lab, target);
    await mkdir(dirname(target), { recursive: true });
    await writeAbsentOrEqual(target, content, label);
  }
  await prepareLabPath(paths.lab, paths.personalSettings);
  await mkdir(dirname(paths.personalSettings), { recursive: true });
  await writeAbsentOrSafeSettings(paths.personalSettings);
  console.log(`个人 Desktop profile 已写入：${paths.personalProfile}`);
  return { paths, config };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writePersonalLabConfig(process.cwd());
}
